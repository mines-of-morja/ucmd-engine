"""A package from the last frame of an H5MD trajectory: the base package with that frame's
positions and box (velocities are regenerated by the NVT run).

usage: python make_package.py TRAJ.h5 BASE.ucsys OUT.ucsys
"""

import json
import shutil
import sys
from pathlib import Path

import h5py
import numpy as np

traj, base, out = (Path(a) for a in sys.argv[1:4])
shutil.copytree(base, out)
with h5py.File(traj, "r") as fh:
    x = np.asarray(fh["particles/all/position/value"][-1], dtype=np.float64)
    box = np.asarray(fh["particles/all/box/edges/value"][-1], dtype=np.float64)
    step = int(fh["particles/all/position/step"][-1])
np.save(out / "positions.npy", x)
(out / "velocities.npy").unlink(missing_ok=True)
doc = json.loads((out / "system.json").read_text())
doc["cell_nm"] = box.tolist()
doc.setdefault("provenance", {})["notes"] = f"last frame (step {step}) of {traj.name}"
(out / "system.json").write_text(json.dumps(doc, indent=1))
print(f"{out}: step {step}, box {box[0, 0]:.4f} nm")
