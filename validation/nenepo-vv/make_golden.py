"""Golden trajectory for E1.5(d): the NeNePo velocity Verlet, reimplemented in atomic units.

    python3 validation/nenepo-vv/make_golden.py > validation/nenepo-vv/golden.txt

Update order of NeNePo_builder `site-packages/VV_8_12.py:72-76` (commit fd7f1e2, see the
UnitcellMD audit):
    q_new = q + v dt + a/2 dt^2          (q_plus_1)
    a_new = -grad(q_new) / m             (grad_to_a)
    v_new = v + (a + a_new)/2 dt         (v_plus_1)
NeNePo's removal of centre-of-mass and rotational motion and its thermostat are not part of the
test: tethered particles have neither invariance.

System: the spec fixture `harmonic-3d` (masses 1, 2, 3 amu; positions and velocities below),
every particle tethered to the origin with k = 1000 kJ mol^-1 nm^-2; dt = 1 fs; 1000 steps.

Units are converted with the spec's CODATA 2018 constants. The electron mass in g/mol is derived
from E_h = m_e a0^2 / t_au^2, so the four conversions are exactly consistent and only the
integration scheme is compared (NeNePo's rounded `aumas` would add a ~1e-9 offset).
"""

import numpy as np

NM_PER_BOHR = 0.0529177210903
KJMOL_PER_HARTREE = 2625.4996394798254
PS_PER_AU_TIME = 2.4188843265857193e-05
ME_G_PER_MOL = KJMOL_PER_HARTREE * PS_PER_AU_TIME**2 / NM_PER_BOHR**2

masses_amu = np.array([1.0, 2.0, 3.0])
q_nm = np.array([[0.1, 0.0, 0.0], [0.0, 0.2, 0.0], [0.0, 0.0, -0.15]])
v_nm_ps = np.array([[0.0, 1.0, 0.0], [0.5, 0.0, 0.0], [0.0, 0.0, -0.2]])
k_kjmol_nm2 = 1000.0
dt_ps = 0.001
steps = 1000
report = {0, 1, 10, 100, 1000}

# to atomic units (flat 3N arrays, as in NeNePo)
m = np.repeat(masses_amu / ME_G_PER_MOL, 3)
k = k_kjmol_nm2 * NM_PER_BOHR**2 / KJMOL_PER_HARTREE
dt = dt_ps / PS_PER_AU_TIME
q = (q_nm / NM_PER_BOHR).ravel()
v = (v_nm_ps * PS_PER_AU_TIME / NM_PER_BOHR).ravel()


def grad(q):
    return k * q


def emit(step, q, v):
    qn = (q * NM_PER_BOHR).reshape(-1, 3)
    vn = (v * NM_PER_BOHR / PS_PER_AU_TIME).reshape(-1, 3)
    for i in range(len(qn)):
        print(step, i, *(f"{x:.17e}" for x in (*qn[i], *vn[i])))


print("# step atom x_nm y_nm z_nm vx_nm_ps vy_nm_ps vz_nm_ps  (generated by make_golden.py)")
a = -grad(q) / m
emit(0, q, v)
for step in range(1, steps + 1):
    q_new = q + v * dt + a / 2 * dt**2
    a_new = -grad(q_new) / m
    v = v + (a + a_new) / 2 * dt
    q, a = q_new, a_new
    if step in report:
        emit(step, q, v)
